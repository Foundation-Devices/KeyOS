use std::{
    env,
    fs::{self, File},
    io::Write,
    path::Path,
    process::Command,
};

use nom::{
    bytes::complete::{tag, take_until},
    character::complete::{alphanumeric1, multispace1, space1},
    IResult,
};

fn parse_define(input: &str) -> IResult<&str, (&str, &str)> {
    let (input, _) = tag("#define")(input)?;
    let (input, _) = space1(input)?;
    let (input, name) = take_until(" ")(input)?;
    let (input, _) = multispace1(input)?;
    let (input, value) = alphanumeric1(input)?;
    Ok((input, (name, value)))
}

fn main() {
    const SDK_NAME: &str = "ledger-secure-sdk";

    let (repo_url, sdk_branch) = (Path::new("https://github.com/LedgerHQ/").join(SDK_NAME), "API_LEVEL_22");

    let bolos_sdk = env::temp_dir().join(SDK_NAME);
    if !bolos_sdk.exists() {
        Command::new("git")
            .arg("clone")
            .arg(repo_url.to_str().unwrap())
            .arg("-b")
            .arg(sdk_branch)
            .arg(bolos_sdk.as_path())
            .output()
            .ok();
    }

    let header_content =
        fs::read_to_string(bolos_sdk.join("include/syscalls.h")).expect("Failed to read file");

    let mut syscall_id_rs = File::create("src/syscall_id.rs").expect("Failed to create file");
    syscall_id_rs.write("// SP".as_bytes()).ok();
    syscall_id_rs
        .write("DX-FileCopyrightText: 2025 Foundation Devices, Inc. <hello@foundation.xyz>\n".as_bytes())
        .ok();
    syscall_id_rs.write("// SP".as_bytes()).ok();
    syscall_id_rs.write("DX-License-Identifier: GPL-3.0-or-later\n\n".as_bytes()).ok();

    syscall_id_rs.write("// This file is generated by update_syscall_ids\n\n".as_bytes()).ok();
    syscall_id_rs.write("#![allow(unused)]\n".as_bytes()).ok();

    for line in header_content.lines() {
        match parse_define(line) {
            Ok((_, (name, value))) => {
                syscall_id_rs
                    .write(format!("pub const {}: u32 = {};\n", name.to_uppercase(), value).as_bytes())
                    .ok();
            }
            Err(_e) => {
                // println!("Failed to parse line: {}", e);
            }
        }
    }
}
