#[inline]
fn color_to_pixel(color: u32) -> Pixel { color & 0x00FF_FFFF }

#[inline]
fn gray_to_pixel(gray: u8) -> Pixel {
    let gray = gray as Pixel;
    (gray << 16) | (gray << 8) | gray
}

#[inline]
fn invert_pixel(pixel: Pixel) -> Pixel {
    let r = 0xFF - ((pixel >> 16) & 0xFF);
    let g = 0xFF - ((pixel >> 8) & 0xFF);
    let b = 0xFF - (pixel & 0xFF);

    // Avoid pure black after inversion — use #212121 as the darkest background.
    if r == 0 && g == 0 && b == 0 {
        DARK_BACKGROUND
    } else {
        (r << 16) | (g << 8) | b
    }
}

fn snapshot_frame(context: &str, invert: bool) -> Option<Frame> {
    let Ok(buf) = DISPLAY_BUFFER.read() else {
        log::warn!("{context}: could not acquire read lock");
        return None;
    };
    if invert {
        Some(buf.iter().copied().map(invert_pixel).collect())
    } else {
        Some(buf.clone())
    }
}

/// Blit a word-pixel buffer (row-major order) into the display framebuffer at (x0, y0).
/// Retained for future use (e.g. QR codes which produce row-major data).
#[allow(dead_code)]
fn blit(buf: &mut [Pixel], x0: usize, y0: usize, w: usize, h: usize, pixels: &[Pixel]) {
    for row in 0..h {
        let dy = y0 + row;
        if dy >= DISPLAY_HEIGHT {
            break;
        }
        for col in 0..w {
            let dx = x0 + col;
            if dx >= DISPLAY_WIDTH {
                break;
            }
            let src = row * w + col;
            let dst = dy * DISPLAY_WIDTH + dx;
            if src < pixels.len() {
                buf[dst] = pixels[src];
            }
        }
    }
}

/// Blit column-first RTL pixel data into the framebuffer.
///
/// Pixel data is in column-first, right-to-left order (as produced by
/// `icon2glyph.py`): the first pixel corresponds to the bottom of the
/// rightmost column, advancing top-to-bottom within each column, then
/// moving right-to-left across columns.
fn blit_column_first(buf: &mut [Pixel], x0: usize, y0: usize, w: usize, h: usize, pixels: &[Pixel]) {
    let total_pixels = pixels.len();
    let mut pixel_idx = 0;
    let mut col = 0;
    let mut row = 0;
    while pixel_idx < total_pixels {
        let dx = x0 + (w - 1 - col);
        let dy = y0 + row;
        if dx < DISPLAY_WIDTH && dy < DISPLAY_HEIGHT {
            let dst = dy * DISPLAY_WIDTH + dx;
            buf[dst] = pixels[pixel_idx];
        }
        pixel_idx += 1;
        row += 1;
        if row >= h {
            row = 0;
            col += 1;
        }
    }
}

/// Convert a 2-bit NBGL grayscale level to an 8-bit value.
/// 0 → 0 (black), 1 → 85, 2 → 170, 3 → 255 (white).
fn gray_level_to_u8(level: u8) -> u8 { (level & 0x03) * 85 }

/// 1bpp: bit=1 → foreground (color_map & 0x03), bit=0 → background (area.color).
/// MSB first within each byte.
/// Note: the SDK's icon2glyph.py inverts 1bpp images before packing, so
/// bit=0 corresponds to the original white (background) pixels and bit=1
/// to the original black (foreground) pixels.
fn decode_1bpp(buffer: &[u8], total_pixels: usize, color_map: u8, bg_color: u8, out: &mut Vec<Pixel>) {
    let fg = gray_level_to_u8(color_map & 0x03);
    let bg = gray_level_to_u8(bg_color & 0x03);

    let mut pixel_count = 0;
    for &byte in buffer {
        for bit_idx in (0..8).rev() {
            if pixel_count >= total_pixels {
                return;
            }
            let bit = (byte >> bit_idx) & 1;
            let g = if bit == 1 { fg } else { bg };
            out.push(gray_to_pixel(g));
            pixel_count += 1;
        }
    }
}

/// 2bpp: 2 bits per pixel → index 0-3. Mapped via color_map (2 bits per entry, MSB first).
fn decode_2bpp(buffer: &[u8], total_pixels: usize, color_map: u8, out: &mut Vec<Pixel>) {
    let mut pixel_count = 0;
    for &byte in buffer {
        for shift in (0..8).step_by(2).rev() {
            if pixel_count >= total_pixels {
                return;
            }
            let idx = (byte >> shift) & 0x03;
            // color_map has 4 entries of 2 bits each, packed MSB first:
            // bits 7-6 = index 0, bits 5-4 = index 1, bits 3-2 = index 2, bits 1-0 = index 3
            let mapped = (color_map >> (6 - idx * 2)) & 0x03;
            let g = gray_level_to_u8(mapped);
            out.push(gray_to_pixel(g));
            pixel_count += 1;
        }
    }
}

/// 4bpp: 4 bits per pixel → 16 levels, interpolated between foreground and background colors.
/// val=0 → foreground, val=15 → background. MSB first.
fn decode_4bpp(buffer: &[u8], total_pixels: usize, color_map: u8, bg_color: u8, out: &mut Vec<Pixel>) {
    let fg = gray_level_to_u8(color_map & 0x03) as u16;
    let bg = gray_level_to_u8(bg_color & 0x03) as u16;
    let mut pixel_count = 0;
    for &byte in buffer {
        for shift in [4, 0] {
            if pixel_count >= total_pixels {
                return;
            }
            let val = (byte >> shift) & 0x0F;
            let g = (fg * (15 - val as u16) + bg * val as u16) / 15;
            out.push(gray_to_pixel(g as u8));
            pixel_count += 1;
        }
    }
}

/// Decode RLE-compressed image data and blit into the framebuffer.
///
/// Pixels are decoded in **column-first** order (right-to-left columns,
/// top-to-bottom within each column) — the layout used by NBGL's
/// `box_to_packed_bitmap(nbgl=true)` encoder. After decoding, pixels are
/// transposed to row-major order for the framebuffer blit.
///
/// `nb_skipped_bytes` skips that many decoded pixels from the start
/// (used for partial character rendering).
pub(crate) fn draw_image_rle(area: NbglArea, bpp: u8, fore_color: u8, buffer: &[u8], nb_skipped_bytes: u8) {
    let w = area.width as usize;
    let h = area.height as usize;

    if w == 0 || h == 0 {
        return;
    }

    let total_pixels = w * h;

    // Zero-length buffer (e.g. space characters): fill with background color.
    if buffer.is_empty() {
        let bg = gray_level_to_u8(area.color & 0x03);
        draw_rect(area.x0, area.y0, area.width, area.height, gray_to_pixel(bg));
        return;
    }

    // Decode RLE into a flat pixel array (column-first order).
    let decoded = match bpp {
        1 => decode_rle_1bpp(buffer, total_pixels, fore_color, area.color),
        4 => decode_rle_4bpp(buffer, total_pixels),
        _ => {
            log::warn!("draw_image_rle: unsupported bpp={bpp}");
            return;
        }
    };

    // Skip pixels (the C code names the param nb_skipped_bytes but the
    // value is computed as a pixel count by the SDK).
    let skip = nb_skipped_bytes as usize;

    // Transpose column-first → row-major and blit.
    let Ok(mut buf) = DISPLAY_BUFFER.write() else {
        log::warn!("draw_image_rle: could not acquire write lock");
        return;
    };

    let mut pixel_idx = skip;
    // Column-first order: col goes from (width-1) down to 0,
    // row goes from 0 up to (height-1) within each column.
    let start_col = pixel_idx / h;
    let start_row = pixel_idx % h;

    let mut col = start_col;
    let mut row = start_row;

    while pixel_idx < decoded.len() && col < w {
        let g = decoded[pixel_idx];
        // Transpose: column-first right-to-left → screen coordinates
        let dx = area.x0 as usize + (w - 1 - col);
        let dy = area.y0 as usize + row;

        if dx < DISPLAY_WIDTH && dy < DISPLAY_HEIGHT {
            let dst = dy * DISPLAY_WIDTH + dx;
            buf[dst] = gray_to_pixel(g);
        }

        pixel_idx += 1;
        row += 1;
        if row >= h {
            row = 0;
            col += 1;
        }
    }
}

/// 1bpp RLE decode: each byte = `ZZZZOOOO`
/// - ZZZZ (high nibble): count of 0-pixels (background color)
/// - OOOO (low nibble): count of 1-pixels (foreground/ink color)
fn decode_rle_1bpp(buffer: &[u8], total_pixels: usize, fore_color: u8, bg_color: u8) -> Vec<u8> {
    let fg = gray_level_to_u8(fore_color & 0x03);
    let bg = gray_level_to_u8(bg_color & 0x03);
    let mut pixels = Vec::with_capacity(total_pixels);

    for &byte in buffer {
        let zeros = (byte >> 4) & 0x0F;
        let ones = byte & 0x0F;

        for _ in 0..zeros {
            if pixels.len() >= total_pixels {
                return pixels;
            }
            pixels.push(bg); // 0-pixel = background
        }
        for _ in 0..ones {
            if pixels.len() >= total_pixels {
                return pixels;
            }
            pixels.push(fg); // 1-pixel = foreground/ink
        }
    }

    // Pad remaining pixels with background if the RLE data is shorter
    while pixels.len() < total_pixels {
        pixels.push(bg);
    }
    pixels
}

/// 4bpp RLE decode. Three byte types:
/// - `0CCCNNNN` (bit7=0): non-white run of CCC+1 pixels of color NNNN
/// - `10PPXXXX` (bits7-6=10): packed singles, PP+3 total pixels (3-6), first pixel = XXXX nibble, remaining
///   packed 2-per-byte after
/// - `11CCCCCC` (bits7-6=11): white run of CCCCCC+1 pixels (color 15)
fn decode_rle_4bpp(buffer: &[u8], total_pixels: usize) -> Vec<u8> {
    let mut pixels = Vec::with_capacity(total_pixels);
    let mut i = 0;

    while i < buffer.len() && pixels.len() < total_pixels {
        let byte = buffer[i];
        i += 1;

        if byte & 0x80 == 0 {
            // Non-white run: 0CCCNNNN
            let count = ((byte >> 4) & 0x07) as usize + 1; // CCC + 1 (1-8)
            let color = byte & 0x0F;
            let g = color * 17;
            for _ in 0..count {
                if pixels.len() >= total_pixels {
                    break;
                }
                pixels.push(g);
            }
        } else if byte & 0xC0 == 0x80 {
            // Packed singles: 10PPXXXX
            let num_pixels = ((byte >> 4) & 0x03) as usize + 3; // PP + 3 (3-6)
            let first_nibble = byte & 0x0F;
            // We have num_pixels total. First pixel is the XXXX nibble.
            // Remaining nibbles are packed 2-per-byte in subsequent bytes.
            let mut nibbles = Vec::with_capacity(num_pixels);
            nibbles.push(first_nibble);
            // Read remaining nibbles from subsequent bytes
            let remaining = num_pixels - 1;
            let bytes_needed = remaining.div_ceil(2);
            for _ in 0..bytes_needed {
                if i >= buffer.len() {
                    break;
                }
                let b = buffer[i];
                i += 1;
                nibbles.push((b >> 4) & 0x0F);
                nibbles.push(b & 0x0F);
            }
            for j in 0..num_pixels {
                if pixels.len() >= total_pixels || j >= nibbles.len() {
                    break;
                }
                pixels.push(nibbles[j] * 17);
            }
        } else {
            // White run: 11CCCCCC
            let count = (byte & 0x3F) as usize + 1; // CCCCCC + 1 (1-64)
            for _ in 0..count {
                if pixels.len() >= total_pixels {
                    break;
                }
                pixels.push(255); // white = color 15 = 15*17 = 255
            }
        }
    }

    // Pad with white if needed
    while pixels.len() < total_pixels {
        pixels.push(255);
    }
    pixels
}

