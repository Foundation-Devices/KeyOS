//! NBGL display framebuffer and draw primitives.
//!
//! The server thread writes into a shared word-pixel framebuffer via `draw_rect`,
//! `draw_horizontal_line`, and `draw_image`. On `NbglRefresh` the buffer is
//! snapshotted and passed to the registered callback.

use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{LazyLock, OnceLock, RwLock};

use ab_glyph::{Font, FontRef, ScaleFont};

use super::{NbglArea, SephTag, SEPH_FIFO};

pub const DISPLAY_WIDTH: usize = 480;
pub const DISPLAY_HEIGHT: usize = 600;
const PIXEL_COUNT: usize = DISPLAY_WIDTH * DISPLAY_HEIGHT;
/// RGB888 display pixel in `0x00RRGGBB` format.
pub type FramePixel = u32;
pub type Frame = Vec<FramePixel>;
type Pixel = FramePixel;

const WHITE: Pixel = 0x00FF_FFFF;
const DARK_BACKGROUND: Pixel = 0x0021_2121;

/// Shared RGB888 framebuffer. Server thread writes, `refresh()` reads.
static DISPLAY_BUFFER: LazyLock<RwLock<Vec<Pixel>>> = LazyLock::new(|| RwLock::new(vec![WHITE; PIXEL_COUNT]));

/// Dark mode state, pushed from the Slint event loop via `set_dark_mode()`.
/// Using an AtomicBool so background threads (flux server, app monitor) can
/// read it safely without going back through Slint's property system.
static IS_DARK_MODE: AtomicBool = AtomicBool::new(false);

/// Update the dark mode state. Must be called from the Slint event loop
/// at startup and whenever the theme changes.
pub fn set_dark_mode(dark: bool) { IS_DARK_MODE.store(dark, Ordering::Relaxed); }

/// Callback invoked to push a new display frame.
/// Set once from the binary crate via `init()`.
static REFRESH_CALLBACK: OnceLock<Box<dyn Fn(Frame) + Send + Sync>> = OnceLock::new();

/// Callback invoked after `reset()` clears the display.
static RESET_CALLBACK: OnceLock<Box<dyn Fn() + Send + Sync>> = OnceLock::new();

/// Register the callback that receives refreshed display images.
///
/// The callback is invoked on the caller's thread each time `NbglRefresh`
/// fires. UI callers must dispatch the callback body to their UI runtime.
pub fn init(cb: impl Fn(Frame) + Send + Sync + 'static) {
    if REFRESH_CALLBACK.set(Box::new(cb)).is_err() {
        log::warn!("display::init called more than once");
    }
}

/// Fill a rectangle in the framebuffer. `color` is `0x00RRGGBB`.
pub fn draw_rect(x0: u16, y0: u16, width: u16, height: u16, color: u32) {
    let Ok(mut buf) = DISPLAY_BUFFER.write() else {
        log::warn!("draw_rect: could not acquire write lock");
        return;
    };

    let pixel = color_to_pixel(color);
    let x_start = (x0 as usize).min(DISPLAY_WIDTH);
    let y_start = (y0 as usize).min(DISPLAY_HEIGHT);
    let x_end = ((x0 as usize) + (width as usize)).min(DISPLAY_WIDTH);
    let y_end = ((y0 as usize) + (height as usize)).min(DISPLAY_HEIGHT);

    for y in y_start..y_end {
        let row_offset = y * DISPLAY_WIDTH;
        buf[row_offset + x_start..row_offset + x_end].fill(pixel);
    }
}

/// Draw a 1-pixel horizontal line.

/// Decode a packed NBGL bitmap and blit it into the framebuffer.
///
/// `bpp` is the *real* bits-per-pixel (1, 2, or 4) after `nbgl_bpp_to_read_bpp`.
/// `color_map` encodes foreground/background grayscale levels.
/// `transformation`: 0x00 = none, 0x02 = vertical mirror, 0x04 = rotate 90° CW.
///
/// Pixel data is in **column-first, right-to-left** order as generated by
/// the SDK's `icon2glyph.py`. The column-first layout is transposed to
/// row-major screen coordinates during blitting, matching `draw_image_rle`.
pub(crate) fn draw_image(area: NbglArea, bpp: u8, transformation: u8, buffer: &[u8], color_map: u8) {
    let w = area.width as usize;
    let h = area.height as usize;

    if w == 0 || h == 0 {
        return;
    }

    if buffer.is_empty() {
        return;
    }

    // Decode all pixels into a word-pixel buffer (column-first order).
    let total_pixels = w * h;
    let mut pixels = Vec::with_capacity(total_pixels);

    match bpp {
        1 => decode_1bpp(buffer, total_pixels, color_map, area.color, &mut pixels),
        2 => decode_2bpp(buffer, total_pixels, color_map, &mut pixels),
        4 => decode_4bpp(buffer, total_pixels, color_map, area.color, &mut pixels),
        _ => {
            log::warn!("draw_image: unsupported bpp={bpp}");
            return;
        }
    }

    // Apply transformation and blit with column-first transpose.
    let Ok(mut buf) = DISPLAY_BUFFER.write() else {
        log::warn!("draw_image: could not acquire write lock");
        return;
    };

    let x0 = area.x0 as usize;
    let y0 = area.y0 as usize;

    match transformation {
        0x00 => {
            // Column-first RTL → screen coordinates (same as draw_image_rle).
            blit_column_first(&mut buf, x0, y0, w, h, &pixels);
        }
        0x02 => {
            // VERTICAL_MIRROR: mirror about the vertical axis = horizontal flip (swap left/right).
            // Normal blit maps column-first (col, row) → screen (x0 + w-1-col, y0 + row).
            // Horizontal flip reverses x: (col, row) → screen (x0 + col, y0 + row).
            let mut pixel_idx = 0;
            let mut col = 0;
            let mut row = 0;
            while pixel_idx < pixels.len() {
                let dx = x0 + col;
                let dy = y0 + row;
                if dx < DISPLAY_WIDTH && dy < DISPLAY_HEIGHT {
                    let dst = dy * DISPLAY_WIDTH + dx;
                    buf[dst] = pixels[pixel_idx];
                }
                pixel_idx += 1;
                row += 1;
                if row >= h {
                    row = 0;
                    col += 1;
                }
            }
        }
        0x04 => {
            // Rotate 90° CW from column-first input.
            // Column-first pixel (col, row) → original screen pos (w-1-col, row).
            // After 90° CW rotation: (x, y) → (h-1-y, x), output is h×w.
            // Combined: column-first (col, row) → rotated screen (h-1-row, w-1-col).
            let mut pixel_idx = 0;
            let mut col = 0;
            let mut row = 0;
            while pixel_idx < pixels.len() {
                let dx = x0 + (h - 1 - row);
                let dy = y0 + (w - 1 - col);
                if dx < DISPLAY_WIDTH && dy < DISPLAY_HEIGHT {
                    let dst = dy * DISPLAY_WIDTH + dx;
                    buf[dst] = pixels[pixel_idx];
                }
                pixel_idx += 1;
                row += 1;
                if row >= h {
                    row = 0;
                    col += 1;
                }
            }
        }
        _ => {
            log::warn!(
                "draw_image: unsupported transformation=0x{transformation:02x}, drawing without transform"
            );
            blit_column_first(&mut buf, x0, y0, w, h, &pixels);
        }
    }
}

/// Snapshot the buffer and pass it to the registered refresh callback.
///
/// Light mode: clone the word-pixel buffer.
/// Dark mode: invert while snapshotting.
pub fn refresh() {
    let Some(cb) = REFRESH_CALLBACK.get() else {
        log::warn!("display::refresh: callback not set (call display::init first)");
        return;
    };

    let is_dark = IS_DARK_MODE.load(Ordering::Relaxed);
    let Some(frame) = snapshot_frame("display::refresh", is_dark) else {
        return;
    };
    cb(frame);
}

/// Register a callback invoked after `reset()` clears the display.
///
/// The callback is invoked on the caller's thread. UI callers must dispatch
/// the callback body to their UI runtime.
pub fn on_reset(cb: impl Fn() + Send + Sync + 'static) {
    if RESET_CALLBACK.set(Box::new(cb)).is_err() {
        log::warn!("display::on_reset called more than once");
    }
}

/// Clear the framebuffer and notify the reset callback.
///
/// Called from the server thread when the Flux app process disconnects.
pub fn reset() {
    clear();

    if let Some(refresh_cb) = REFRESH_CALLBACK.get() {
        if let Some(frame) = snapshot_frame("display::reset", false) {
            refresh_cb(frame);
        }
    }
    if let Some(reset_cb) = RESET_CALLBACK.get() {
        reset_cb();
    }
}

/// Fill buffer with the background color: white in light mode, #212121 in dark mode.
pub fn clear() {
    if let Ok(mut buf) = DISPLAY_BUFFER.write() {
        let is_dark = IS_DARK_MODE.load(Ordering::Relaxed);
        if is_dark {
            buf.fill(DARK_BACKGROUND);
        } else {
            buf.fill(WHITE);
        }
    }
}

/// Build a SEPH FingerEvent TLV and push it to `SEPH_FIFO`.
///
/// Format: `[0x0c, 0x00, 0x05, state, x_hi, x_lo, y_hi, y_lo]`
/// State: 1 = pressed, 0 = released.
pub fn push_touch_event(x: i16, y: i16, state: u8) {
    let x_bytes = x.to_be_bytes();
    let y_bytes = y.to_be_bytes();
    let pkt =
        vec![SephTag::FingerEvent.into(), 0x00, 0x05, state, x_bytes[0], x_bytes[1], y_bytes[0], y_bytes[1]];

    if let Ok(mut fifo) = SEPH_FIFO.write() {
        log::trace!(
            "push_touch_event: x={x}, y={y}, state={state}, pkt={pkt:02x?}, fifo_len={}",
            fifo.len() + 1
        );
        fifo.push_back(pkt);
    } else {
        log::error!("push_touch_event: failed to acquire SEPH_FIFO write lock");
    }
}

